// 名前入力のカーソルが動ける範囲。
// 原版は升の数を前提にした値を直に書いているので、表から数えた総数（$0030,X）に合わせる

// 画面に入るときのカーソル位置。升目の末尾＝決定のキーを指す。
// 日本語版は 60 升なので、末尾は 0x3B になる。
// 直後の `LDX $22` は名前が空のときの再入（`cd:82e8`）の飛び先なので触れない。
// 書き換えられるのは 3 バイトだけで、表を数えるコードは入らないので、値を直に書く。
// 表の升の数がこの値と合うことは、packages/features/name-entry/name_table.ts が確かめる
org $CD82CB
	LDA #$003B

// 右キーを押すとカーソルを 1 つ進め、升目の総数に届いたらカーソルを先頭の升へ戻す
org $CCB8C4
	db $DD,$30,$00		// CMP $0030,X

// 先頭で左を押したときは、総数から 1 を引いた升へ送る。書き換えは原版と同じ 12 バイトに収める
org $CCB89D
	db $BD,$36,$00		// LDA $0036,X。カーソル
	db $D0,$03		// BNE。先頭でなければ 1 つ戻すだけ
	db $BD,$30,$00		// LDA $0030,X。総数
	db $3A			// DEC A
	db $9D,$36,$00		// STA $0036,X
